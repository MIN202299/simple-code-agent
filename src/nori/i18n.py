"""Interface language. English is the default; Chinese is available.

English text is the key: `t("Saved to {path}", path=p)` returns the translation
for the current language, or the English text itself. The Chinese catalog is in
`ZH` below; a test checks that every `t("...")` in the code has an entry.
"""

from __future__ import annotations

LANGUAGES = {"en": "English", "zh": "中文"}
DEFAULT_LANGUAGE = "en"

_language = DEFAULT_LANGUAGE


def normalize_language(code: str | None) -> str | None:
    """Map user input such as `zh-CN`, `Chinese` or `EN` to a supported code."""
    if not code:
        return None
    code = code.strip().lower().replace("_", "-")
    if code.startswith("zh") or code in ("cn", "chinese", "中文"):
        return "zh"
    if code.startswith("en") or code == "english":
        return "en"
    return None


def set_language(code: str | None) -> bool:
    """Switch the interface language. Returns False for an unsupported one."""
    global _language
    normalized = normalize_language(code)
    if normalized is None:
        return False
    _language = normalized
    return True


def get_language() -> str:
    return _language


def t(text: str, **values: object) -> str:
    """Translate `text` into the current language and fill in `{placeholders}`."""
    template = ZH.get(text, text) if _language == "zh" else text
    return template.format(**values) if values else template


