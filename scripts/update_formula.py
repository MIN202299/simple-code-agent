#!/usr/bin/env python3
"""Write the Homebrew formula for a release.

    python scripts/update_formula.py v0.1.0 <sha256 of the macOS archive> <sha256 of the Linux archive>

The release workflow runs this after publishing and commits the result.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPOSITORY = "MIN202299/simple-code-agent"
FORMULA = Path(__file__).resolve().parent.parent / "Formula" / "nori.rb"

TEMPLATE = '''# Generated by scripts/update_formula.py for each release; do not edit by hand.
class Nori < Formula
  desc "AI coding agent for the terminal"
  homepage "https://github.com/{repository}"
  version "{version}"

  on_macos do
    depends_on arch: :arm64
    url "https://github.com/{repository}/releases/download/{tag}/nori-macos-arm64.tar.gz"
    sha256 "{macos}"
  end

  on_linux do
    depends_on arch: :x86_64
    url "https://github.com/{repository}/releases/download/{tag}/nori-linux-x86_64.tar.gz"
    sha256 "{linux}"
  end

  def install
    # The archive is a self-contained folder: the executable plus its libraries.
    libexec.install Dir["*"]
    bin.write_exec_script libexec/"nori"
  end

  test do
    assert_match "nori", shell_output("#{{bin}}/nori --version")
  end
end
'''


def main() -> int:
    if len(sys.argv) != 4 or any(len(digest) != 64 for digest in sys.argv[2:]):
        print(__doc__)
        return 2
    tag, macos, linux = sys.argv[1:]
    FORMULA.parent.mkdir(exist_ok=True)
    FORMULA.write_text(
        TEMPLATE.format(
            repository=REPOSITORY, tag=tag, version=tag.removeprefix("v"), macos=macos, linux=linux
        ),
        encoding="utf-8",
    )
    print(f"wrote {FORMULA} for {tag}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
